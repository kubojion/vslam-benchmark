#!/usr/bin/env python3
"""Compute the verified numbers behind every prose claim in the report.

Usage:
    python3 verify_claims.py

Writes docs/generated/verified-claims.md. Adopts the "no naked numbers" rule
(2026-08-05): every numeric claim in report prose must trace to a table cell or
to a line in this file's output. Re-run after any CSV rebuild.
"""
from __future__ import annotations
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "docs" / "generated" / "verified-claims.md"


def load(rt):
    df = pd.read_csv(REPO / f"benchmark-{rt}.csv")
    if "gnss_variant" not in df.columns:
        df["gnss_variant"] = "default"
    df["gnss_variant"] = df["gnss_variant"].fillna("default")
    return df


def main() -> int:
    vo, volc, vio, violc, gnss = (load(t) for t in
                                  ["vo", "vo-lc", "vio", "vio-lc", "gnss-vio"])
    L = ["# Verified claim numbers (auto-generated by scripts/eval/verify_claims.py)\n",
         "Every prose claim in the report must cite a table cell or a line below.\n"]

    def add(title, text):
        L.append(f"## {title}\n{text}\n")

    # --- VINS-Fusion seq5 -----------------------------------------------------
    r = gnss[(gnss.algo == "vins_fusion_gps") & (gnss.seq == "sequence5")
             & (gnss.gnss_variant == "default")]
    if len(r):
        r = r.iloc[0]
        add("VINS-Fusion+GPS on Rosario seq5",
            f"ATE Sim3 {r.ate_sim3_rmse_m:.3f} m, SE3 {r.ate_se3_rmse_m:.3f} m over a "
            f"{r.sequence_duration_s/60:.1f}-minute sequence "
            f"({r.sequence_duration_s:.0f} s). "
            f"Do NOT quote '0.4–0.9 m' or '15-minute' — the 0.49 figure was the old "
            f"unaligned final_drift metric and the sequence is ~13 min.")

    # --- AirSLAM fps ----------------------------------------------------------
    a_vio = pd.to_numeric(vio[vio.algo == "airslam"]["fps"], errors="coerce").dropna()
    a_violc = pd.to_numeric(violc[violc.algo == "airslam"]["fps"], errors="coerce").dropna()
    add("AirSLAM speed",
        f"VIO fps range {a_vio.min():.1f}–{a_vio.max():.1f}; "
        f"VIO-LC fps range {a_violc.min():.2f}–{a_violc.max():.2f}. "
        f"The old claim '1.4–3.6 fps slowest VIO' was the VIO-LC range. "
        f"CAVEAT: AirSLAM fps counts keyframe poses only and runs offline — not "
        f"comparable to ROS-fed algorithms (see feeding-regime note).")

    # --- OKVIS2-X vs OKVIS2 speed --------------------------------------------
    rows = []
    for rt_name, df in (("vo", vo), ("vio", vio), ("vio-lc", violc)):
        m = df.pivot_table(index=["dataset", "seq"], columns="algo",
                           values="duration_s", aggfunc="median")
        if "okvis2" in m and "okvis2x" in m:
            ratio = (m["okvis2"] / m["okvis2x"]).dropna()
            for k, v in ratio.items():
                rows.append(f"  {rt_name} {k[0]}/{k[1]}: x{v:.2f}")
    add("OKVIS2-X speedup over OKVIS2 (wall-clock ratio, median)",
        "\n".join(rows) + "\nClaim '~2x faster' holds only on isolated cells; "
        "typical is 0.8–1.5x. State the range, not '2x'.")

    # --- EuRoC scale sanity ---------------------------------------------------
    eu = vo[(vo.dataset == "euroc_mav") & (~vo.algo.isin(["dpvo", "droidslam"]))]
    sc = pd.to_numeric(eu["scale_factor"], errors="coerce").dropna()
    add("EuRoC stereo scale sanity",
        f"{len(sc)} stereo EuRoC VO runs: mean scale {sc.mean():.4f}, "
        f"max |scale-1| {np.abs(sc-1).max()*100:.2f}%. "
        f"(Old '1.001 over 39 runs' is stale.)")

    # --- Basalt Rosario scale -------------------------------------------------
    b = vo[(vo.algo == "basalt") & (vo.dataset == "rosariov2")]
    bs = pd.to_numeric(b["scale_factor"], errors="coerce").dropna()
    if len(bs):
        add("Basalt VO scale drift on Rosario",
            f"scale range {bs.min():.3f}–{bs.max():.3f} "
            f"(|error| {abs(1-bs).min()*100:.1f}–{abs(1-bs).max()*100:.1f}%).")

    # --- ORB-SLAM3 non-determinism -------------------------------------------
    rows = []
    for (ds, seq), g in vo[vo.algo == "orbslam3"].groupby(["dataset", "seq"]):
        v = pd.to_numeric(g["ate_sim3_rmse_m"], errors="coerce").dropna()
        if len(v) >= 3:
            rows.append(f"  {ds}/{seq}: N={len(v)} ATE {v.min():.2f}–{v.max():.2f} m "
                        f"(x{v.max()/v.min():.1f})")
    add("ORB-SLAM3 run-to-run spread (N>=3 VO cells)", "\n".join(rows) or "  n/a")

    # --- IMU effect per dataset (VO vs VIO medians, same algo) ---------------
    rows = []
    for ds in ["rosariov2", "hortimulti", "zed2i", "euroc_mav"]:
        vo_m = vo[vo.dataset == ds].groupby("algo")["ate_sim3_rmse_m"].median()
        vio_m = vio[vio.dataset == ds].groupby("algo")["ate_sim3_rmse_m"].median()
        common = sorted(set(vo_m.index) & set(vio_m.index) - {"dpvo", "droidslam"})
        deltas = [f"{a}: {vo_m[a]:.2f}->{vio_m[a]:.2f}" for a in common]
        rows.append(f"  {ds}: " + "; ".join(deltas))
    add("IMU effect (median ATE Sim3, VO -> VIO, per dataset)", "\n".join(rows))

    # --- LC effect (VO -> VO-LC, per algo/seq) --------------------------------
    rows = []
    vo_m = vo.groupby(["algo", "dataset", "seq"])["ate_sim3_rmse_m"].median()
    for (a, ds, seq), g in volc.groupby(["algo", "dataset", "seq"]):
        v = pd.to_numeric(g["ate_sim3_rmse_m"], errors="coerce").median()
        key = (a if a != "dpvo" else "dpvo", ds, seq)
        if key in vo_m.index and vo_m[key] > 0:
            pct = (v - vo_m[key]) / vo_m[key] * 100
            if abs(pct) > 100:
                rows.append(f"  {a} {ds}/{seq}: {vo_m[key]:.2f}->{v:.2f} ({pct:+.0f}%)")
    add("Loop-closure blow-ups (|change| > 100% vs same-algo VO)",
        "\n".join(rows) or "  none")

    # --- Coverage of ORB agri VO ---------------------------------------------
    o = vo[(vo.algo == "orbslam3") & (vo.dataset.isin(["rosariov2", "hortimulti"]))]
    cov = pd.to_numeric(o["coverage_gap_pct"], errors="coerce").dropna()
    if len(cov):
        add("ORB-SLAM3 agricultural VO coverage (gap-aware)",
            f"range {cov.min():.0f}–{cov.max():.0f}% across {len(cov)} runs.")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L))
    print(f"[claims] wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
