#!/usr/bin/env python3
"""Generate inventory-checked tables with explicit outcomes and cohort separation.

--check compares rendered bytes and source CSVs without modifying any output.
"""
from __future__ import annotations
import argparse
from collections import defaultdict
from pathlib import Path

from build_benchmark_csv import REPO, RUN_TYPES, build_rows, csv_text, load_inventory, preserved_write
from _aggregate_runs import summarize_cell

SEQ_LABEL = {
    ("rosariov2", "sequence1"): "seq1",
    ("rosariov2", "sequence5"): "seq5",
    ("hortimulti", "strawberry02"): "str02",
    ("hortimulti", "strawberry03"): "str03",
    ("zed2i", "field1_110426_full_10fps_q90"): "zed2i",
    ("euroc_mav", "MH_01_easy"): "MH01",
    ("euroc_mav", "MH_03_medium"): "MH03",
    ("euroc_mav", "MH_05_difficult"): "MH05",
}

AGRI_ORDER = ["seq1", "seq5", "str02", "str03", "zed2i"]

EUROC_ORDER = ["MH01", "MH03", "MH05"]

ALGO_LABEL = {
    "orbslam3": "ORB-SLAM3", "ov2slam": "OV2SLAM", "macvo": "MAC-VO",
    "basalt": "Basalt", "airslam": "AirSLAM", "okvis2": "OKVIS2",
    "okvis2x": "OKVIS2-X", "openvins": "OpenVINS", "voxel_svio": "Voxel-SVIO",
    "dpvo": "DPVO (mono)", "droidslam": "DROID-SLAM",
    "vins_fusion_gps": "VINS-Fusion+GPS", "rtabmap_gps": "RTAB-Map+GPS",
    "cifasis_gnss_si": "CIFASIS GNSS-SI", "openvins_gps": "OpenVINS+GPS",
}

HEADER_NOTE = """<!-- Generated by scripts/eval/make_report_tables.py; do not transcribe results by hand. -->

Primary ATE RMSE [m]: **SE(3)** for metric stereo/VIO; **Sim(3)** for monocular DPVO.
Values are conditional on numerically valid saved trajectories, with median
(min–max) for N≥2 and a single value for N=1. Every cell shows evaluated/planned
counts and missing/failure outcomes. A/E/S/F denote attempts/evaluated trajectories/
clean final exports/observed failures. Distinct recorded cohorts are not pooled.
`blocked` means the values are not yet publication qualified; `limited` permits
only the stated limited claim; `observed failure` retains an adverse outcome. `✅ N=3` requires
three completed verified same-cohort attempts, including recorded failures. It does
not guarantee full coverage or successful tracking. No ranking or winner bolding is inferred from
partial coverage, unknown coverage, sparse keyframes, or unqualified results.

Dense coverage measures exported poses on the camera timeline, separately from
reference-supported score coverage. Missing ground truth is not a tracking failure.
EuRoC AirSLAM VIO/VIO-LC uses the fixed corrected cohort (physical runs 4–6,
logical repetitions 1–3). Original affected runs 1–3 remain in
`benchmark-historical-cohorts.csv` and separate reports. OpenVINS retains its
original run1 alongside new runs2–3, with implementation cohorts shown separately.
Sparse keyframe accuracy is not a dense-frame comparison. Unknown instrumentation
remains unknown. Aligned shape ATE does not establish GNSS global accuracy.
"""


def metric_text(stats):
    if stats['n']==0:return 'no valid score'
    text=f"{stats['median']:.4g}"
    if stats['n']>=2:text+=f" ({stats['min']:.4g}–{stats['max']:.4g})"
    return text+f" [score N={stats['n']}]"


def cell_text(rows):
    result=summarize_cell(rows)
    groups=result['cohorts']
    pieces=[]
    for group in groups:
        label=f"cohort {group['cohort'][:10]}: " if len(groups)>1 else ''
        pieces.append(label+metric_text(group['conditional_primary_ate']))
    if not groups:pieces=['no attempt']
    pieces.append(f"A{result['attempt_count']}/E{result['evaluated_trajectory_count']}/S{result['successful_run_count']}/F{result['observed_failure_count']}")
    if result['unknown_outcome_count']:pieces.append(f"U{result['unknown_outcome_count']}")
    outcomes=[f'{count} {status}' for status,count in sorted(result['outcomes'].items()) if status!='ok']
    if outcomes:pieces.append(', '.join(outcomes))
    crashes=sum(r['process_exit_code'] not in (None,0) for r in rows)
    if crashes:pieces.append(f'{crashes} nonzero exit')
    if any(r['scientific_status']=='rerun_required' for r in rows):pieces.append('rerun required')
    if any(r['export_kind']=='keyframes' for r in rows):pieces.append('keyframes')
    dense=[r['coverage_gap_pct'] for r in rows if r['eval_schema']==3]
    if dense and all(v is not None for v in dense):pieces.append(f'coverage ≥{min(dense):.1f}%')
    elif dense:pieces.append('dense coverage unknown')
    if result['protocol_verified_n3']:pieces.append('✅ Protocol N=3')
    else:pieces.append('protocol '+result['protocol_state'])
    pieces.append(', '.join(f'{key}: {value}' for key,value in sorted(result['acceptance'].items())))
    labels=sorted({r['implementation_label'] for r in rows if r.get('implementation_label') and 'historical recorded' not in r['implementation_label']})
    pieces.extend(labels)
    if 'native_shutdown_error_despite_wrapper_exit_zero' in result['claim_limits']:pieces.append('native shutdown error')
    return '; '.join(pieces)


def build_table(rows,sequence_order):
    lines=['| Algorithm (primary alignment) | '+' | '.join(sequence_order)+' |',
           '|---|'+'---|'*len(sequence_order)]
    for algo in [a for a in ALGO_LABEL if any(r['algo']==a for r in rows)]:
        cells=[ALGO_LABEL[algo]+(' — Sim(3)' if algo=='dpvo' else ' — SE(3)')]
        for seq in sequence_order:
            selected=[r for r in rows if r['algo']==algo and SEQ_LABEL.get((r['dataset'],r['seq']))==seq]
            cells.append(cell_text(selected) if selected else 'outside scope')
        lines.append('| '+' | '.join(cells)+' |')
    return '\n'.join(lines)


def loop_events(rows):
    # Repeat-level log observations, never an accepted-loop count or synthetic 0.
    lines=['| Algorithm | Sequence | Variant | Run | Log-reported events |', '|---|---|---|---|---|']
    for row in rows:
        if not row['attempt_exists']:continue
        n=row['loop_closures']
        lines.append(f"| {ALGO_LABEL.get(row['algo'],row['algo'])} | {SEQ_LABEL.get((row['dataset'],row['seq']),row['seq'])} | "
                     f"{row['gnss_variant']} | {row['run']} | {n if n is not None else 'unknown'} |")
    return '\n'.join(lines)


def render_tables(rows):
    outputs={};combined=['# Benchmark result tables', '', HEADER_NOTE]
    for mode in RUN_TYPES:
        mode_rows=[r for r in rows if r['run_type']==mode]
        main=[r for r in mode_rows if r['gnss_variant']=='default']
        parts=[f'# {mode.upper()} results', '', HEADER_NOTE]
        for scope,order in [('Agricultural',AGRI_ORDER),('EuRoC reference control',EUROC_ORDER)]:
            selected=[r for r in main if SEQ_LABEL.get((r['dataset'],r['seq'])) in order]
            present=[s for s in order if any(SEQ_LABEL.get((r['dataset'],r['seq']))==s for r in selected)]
            if present:parts+=['',f'## {scope} — primary ATE RMSE [m]', '', build_table(selected,present)]
        if mode.endswith('lc'):parts+=['', '## Log observations (not verified accepted loops)', '', loop_events(mode_rows)]
        if mode=='gnss-vio':
            variants=defaultdict(list)
            for row in mode_rows:
                if row['gnss_variant']!='default':variants[(row['algo'],row['dataset'],row['seq'],row['gnss_variant'])].append(row)
            parts+=['', '## Legacy GNSS input variants (separate experiments)', '',
                    '| Algorithm | Dataset/sequence | Input variant | Result |', '|---|---|---|---|']
            for (algo,ds,seq,variant),group in sorted(variants.items()):
                parts.append(f'| {ALGO_LABEL.get(algo,algo)} | {ds}/{seq} | {variant} | {cell_text(group)} |')
            parts+=['', 'GNSS global error remains unqualified: historical coordinate origins, antenna lever arms '
                    'and reference independence are not established. SE(3)/Sim(3) values describe aligned shape. '
                    'Invalid-orientation trajectories retain failed full-pose status; any recovered position-only '
                    'diagnostic is separate in the CSV and is not a qualified score.']
        rendered='\n'.join(parts)+'\n';outputs[f'tables-{mode}.md']=rendered
        combined+=['', f'## Mode: {mode.upper()}', '', '\n'.join(parts[3:])]
    outputs['tables.md']='\n'.join(combined)+'\n'
    return outputs


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check',action='store_true')
    ap.add_argument('--inventory',type=Path,default=REPO/'results/repair-20261001/inventory.json')
    ap.add_argument('--csv-dir',type=Path,default=REPO)
    ap.add_argument('--output-dir',type=Path,default=REPO/'docs/generated')
    args=ap.parse_args();rows=build_rows(load_inventory(args.inventory));errors=[]
    # Rendering cannot bless an old CSV while secretly taking values elsewhere.
    for mode in RUN_TYPES:
        source=args.csv_dir/f'benchmark-{mode}.csv'
        if not source.is_file() or source.read_text()!=csv_text([r for r in rows if r['run_type']==mode]):
            errors.append(f'stale source CSV: {source}')
    if errors:
        for error in errors:print(error)
        return 1
    for name,content in render_tables(rows).items():
        path=args.output_dir/name
        if args.check:
            if not path.is_file() or path.read_text()!=content:errors.append(f'stale table: {path}')
        else:preserved_write(path,content)
    print(f'[tables] {"check" if args.check else "render"}: {len(errors)} stale outputs')
    for error in errors:print(error)
    return bool(errors)


if __name__=='__main__':raise SystemExit(main())
